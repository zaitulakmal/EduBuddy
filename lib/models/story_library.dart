/// The storybook library added in database version 9.
///
/// The three original books live as hand-drawn painters keyed by their row id
/// in `story_scene.dart`. These are data instead: every page names a
/// [StoryShot] — a backdrop plus a few placed actors — and `StoryStage` draws
/// it. Rows are matched to this list by [StorySeed.key], which is stored on the
/// `storybooks.story_key` column, so ids never have to line up.
///
/// Three strands: good values, Malaysian culture, and science & nature.
library;

