enum StoryFeel { happy, sad, surprised, sleepy }

enum StoryMotion { still, bob, sway, float, hop, fly }

/// One actor placed on a page. [x] and [y] are the actor's centre as fractions
/// of the page; [size] is its height as a fraction of the page's short side.
class StorySpot {
  final StoryActor actor;
  final double x;
  final double y;
  final double size;
  final StoryFeel feel;
  final StoryMotion motion;
  final bool flip;

  /// Optional ARGB override for the actor's main colour (shirt, wings, planet).
  final int? tint;

  const StorySpot(
    this.actor,
    this.x,
    this.y,
    this.size, {
    this.feel = StoryFeel.happy,
    this.motion = StoryMotion.bob,
    this.flip = false,
    this.tint,
  });
}

class StoryShot {
  final StoryBackdrop backdrop;
  final bool night;
  final bool rain;
  final List<StorySpot> actors;

  const StoryShot(this.backdrop, this.actors, {this.night = false, this.rain = false});
}

class StoryPageSeed {
  final String text;
  final String textMs;
  final StoryShot shot;

  const StoryPageSeed(this.text, this.textMs, this.shot);
}

class StorySeed {
  final String key;
  final String title;
  final String titleMs;
  final String description;
  final String coverEmoji;

  /// Matched by name against the `categories` table.
  final String category;
  final String ageGroup;
  final List<StoryPageSeed> pages;

  const StorySeed({
    required this.key,
    required this.title,
    required this.titleMs,
    required this.description,
    required this.coverEmoji,
    required this.category,
    required this.ageGroup,
    required this.pages,
  });
}

StorySeed? storySeedFor(String? key) {
  if (key == null) return null;
  for (final s in kStoryLibrary) {
    if (s.key == key) return s;
  }
  return null;
}

